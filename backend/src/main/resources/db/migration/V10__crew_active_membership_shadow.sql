CREATE FUNCTION crew_active_check_children() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME='crew_active_projection_member' THEN
  IF NOT EXISTS(SELECT 1 FROM crew_person_external_id x WHERE x.source='LAUNCH_LIBRARY_2' AND x.person_id=NEW.person_id AND 'LL2:PERSON:'||x.external_id=NEW.human_key) THEN
   RAISE EXCEPTION 'Shadow human must be its typed LL2 provider anchor' USING ERRCODE='23514';
  END IF;
  IF NEW.departure_evidence_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_verification_evidence e WHERE e.id=NEW.departure_evidence_id AND e.evidence_type='PERSON_DEPARTED_STATION' AND e.assertion='COMPLETED') THEN
   RAISE EXCEPTION 'Member veto is not a completed named departure' USING ERRCODE='23514';
  END IF;
 ELSIF TG_TABLE_NAME='crew_active_projection_evidence' THEN
  IF NOT EXISTS(SELECT 1 FROM crew_verification_evidence e JOIN crew_active_projection_revision p ON p.id=NEW.projection_id WHERE e.id=NEW.evidence_id AND e.document_id=NEW.document_id AND p.input_cut->'evidence' @> to_jsonb(ARRAY[NEW.evidence_id])) THEN
   RAISE EXCEPTION 'Wrong operational evidence cut' USING ERRCODE='23514';
  END IF;
 ELSE
  IF NEW.sync_run_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_source_sync_run r JOIN crew_active_projection_revision p ON p.id=NEW.projection_id WHERE r.id=NEW.sync_run_id AND r.completed_at<=p.evaluated_at AND (NEW.document_id IS NULL OR r.verification_document_id=NEW.document_id)) THEN
   RAISE EXCEPTION 'Wrong source run/capture cut' USING ERRCODE='23514';
  END IF;
  IF NEW.acquisition_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_editorial_acquisition a JOIN crew_active_projection_revision p ON p.id=NEW.projection_id WHERE a.id=NEW.acquisition_id AND a.completed_at<=p.evaluated_at AND a.stream=NEW.stream) THEN
   RAISE EXCEPTION 'Wrong editorial health cut' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_active_member_owner BEFORE INSERT ON crew_active_projection_member FOR EACH ROW EXECUTE FUNCTION crew_active_check_children();
CREATE TRIGGER crew_active_evidence_owner BEFORE INSERT ON crew_active_projection_evidence FOR EACH ROW EXECUTE FUNCTION crew_active_check_children();
CREATE TRIGGER crew_active_capture_owner BEFORE INSERT ON crew_active_projection_input_capture FOR EACH ROW EXECUTE FUNCTION crew_active_check_children();
CREATE FUNCTION crew_active_validate_complete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM crew_active_projection_member m WHERE m.projection_id=NEW.id AND m.departure_evidence_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_active_projection_evidence e WHERE e.projection_id=m.projection_id AND e.evidence_id=m.departure_evidence_id)) THEN
  RAISE EXCEPTION 'Member veto outside pinned evidence cut' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM crew_active_projection_member m WHERE m.projection_id=NEW.id AND m.state='ACTIVE' AND NOT EXISTS(SELECT 1 FROM crew_active_projection_support s WHERE s.projection_id=m.projection_id AND s.human_key=m.human_key AND s.eligible)) THEN
  RAISE EXCEPTION 'ACTIVE requires an eligible source support' USING ERRCODE='23514';
 END IF;
 IF (SELECT count(*) FROM crew_active_projection_member WHERE projection_id=NEW.id AND state='ACTIVE')<>(NEW.result->'counts'->>'resolvedActiveHumans')::int
 OR (SELECT count(*) FROM crew_active_projection_member WHERE projection_id=NEW.id AND state='RETAINED')<>(NEW.result->'counts'->>'retainedHumans')::int
 OR (SELECT count(*) FROM crew_active_projection_slot WHERE projection_id=NEW.id AND state='UNRESOLVED_ACTIVE_SOURCE_SLOT')<>(NEW.result->'counts'->>'unresolvedActiveSlots')::int THEN
  RAISE EXCEPTION 'Incomplete shadow projection' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER crew_active_atomic_complete AFTER INSERT ON crew_active_projection_revision DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION crew_active_validate_complete();

-- A committed revision is sealed: even INSERT cannot change its normalized children later.
CREATE FUNCTION crew_active_require_open_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM crew_active_projection_revision r WHERE r.id=NEW.projection_id
   AND r.xmin::text::numeric=mod(pg_current_xact_id()::text::numeric,4294967296)) THEN
  RAISE EXCEPTION 'Shadow projection revision is sealed' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['crew_active_projection_member','crew_active_projection_support','crew_active_projection_slot','crew_active_projection_finding','crew_active_projection_evidence','crew_active_projection_input_capture'] LOOP
  EXECUTE format('CREATE TRIGGER %I BEFORE INSERT ON %I FOR EACH ROW EXECUTE FUNCTION crew_active_require_open_revision()', 'aa_'||t||'_sealed',t);
 END LOOP;
END $$;
