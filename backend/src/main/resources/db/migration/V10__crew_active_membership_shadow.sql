-- ADR-0016. Independent membership overlay; no V1-V9 source or decision rewrites.
CREATE TABLE crew_active_projection_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 predecessor_id bigint REFERENCES crew_active_projection_revision(id),
 policy_version varchar(500) NOT NULL,
 identity_mode varchar(40) NOT NULL CHECK(identity_mode='V9_AUTOMATIC_SHADOW'),
 evaluated_at timestamptz NOT NULL, created_at timestamptz NOT NULL,
 ll2_run_id bigint REFERENCES crew_source_sync_run(id),
 ll2_snapshot_id bigint REFERENCES crew_source_snapshot(id),
 roster_acquisition_id bigint REFERENCES crew_editorial_acquisition(id),
 roster_id bigint REFERENCES crew_editorial_roster_version(id),
 topic_acquisition_id bigint REFERENCES crew_editorial_acquisition(id),
 topic_count_fact_id bigint REFERENCES crew_editorial_topic_fact(id),
 graph_id bigint REFERENCES crew_auto_graph_revision(id),
 operational_run_id bigint REFERENCES crew_source_sync_run(id),
 operational_attempt_id bigint REFERENCES crew_source_sync_run(id),
 input_hash varchar(64) NOT NULL CHECK(input_hash ~ '^[0-9a-f]{64}$'),
 semantic_hash varchar(64) NOT NULL CHECK(semantic_hash ~ '^[0-9a-f]{64}$'),
 serialized_cut text NOT NULL, input_cut jsonb NOT NULL CHECK(input_cut=serialized_cut::jsonb),
 serialized_result text NOT NULL, result jsonb NOT NULL CHECK(result=serialized_result::jsonb),
 health varchar(20) NOT NULL CHECK(health IN ('HEALTHY','DEGRADED','UNAVAILABLE')),
 CHECK(created_at>=evaluated_at),
 CHECK(input_hash=encode(sha256(convert_to(serialized_cut,'UTF8')),'hex')),
 CHECK(semantic_hash=encode(sha256(convert_to(serialized_result,'UTF8')),'hex')),
 CHECK(result->'cut'=input_cut AND result->>'policy'=policy_version AND result->>'health'=health),
 CHECK((roster_id IS NULL)=(roster_acquisition_id IS NULL)),
 CHECK(topic_count_fact_id IS NULL OR topic_acquisition_id IS NOT NULL),
 UNIQUE(predecessor_id), UNIQUE(id,graph_id)
);
CREATE UNIQUE INDEX crew_active_root_idx ON crew_active_projection_revision((true)) WHERE predecessor_id IS NULL;
CREATE INDEX crew_active_latest_idx ON crew_active_projection_revision(created_at DESC,id DESC);
CREATE TABLE crew_active_projection_member (
 projection_id bigint NOT NULL REFERENCES crew_active_projection_revision(id),
 human_key varchar(240) NOT NULL CHECK(human_key LIKE 'LL2:PERSON:%'),
 person_id uuid NOT NULL REFERENCES crew_person(id),
 state varchar(20) NOT NULL CHECK(state IN ('ACTIVE','RETAINED')),
 profile_snapshot_id bigint,
 departure_evidence_id bigint REFERENCES crew_verification_evidence(id),
 payload jsonb NOT NULL CHECK(jsonb_typeof(payload)='object'),
 PRIMARY KEY(projection_id,human_key), UNIQUE(projection_id,person_id),
 FOREIGN KEY(profile_snapshot_id,person_id) REFERENCES crew_person_observation(snapshot_id,person_id)
);
CREATE INDEX crew_active_member_state_idx ON crew_active_projection_member(projection_id,state);
CREATE TABLE crew_active_projection_support (
 projection_id bigint NOT NULL, human_key varchar(240) NOT NULL,
 support_key varchar(300) NOT NULL, support_type varchar(40) NOT NULL CHECK(support_type IN ('LL2_ASSIGNMENT','NASA_EDITORIAL_ROSTER','NASA_OPERATIONAL_POSITIVE','QUALIFIED_REENTRY')),
 stream varchar(50) NOT NULL, captured_at timestamptz NOT NULL, effective_at timestamptz,
 precision varchar(80) NOT NULL, freshness varchar(20) NOT NULL CHECK(freshness IN ('FRESH','STALE','NO_DATA')),
 eligible boolean NOT NULL, snapshot_id bigint, expedition_id uuid, person_id uuid,
 acquisition_id bigint REFERENCES crew_editorial_acquisition(id), roster_id bigint, member_index integer,
 evidence_id bigint, subject_index integer,
 decision_id bigint REFERENCES crew_auto_decision_revision(id), observation_id bigint REFERENCES crew_auto_observation(id),
 departure_evidence_id bigint REFERENCES crew_verification_evidence(id),
 payload jsonb NOT NULL CHECK(jsonb_typeof(payload)='object'),
 PRIMARY KEY(projection_id,human_key,support_key),
 FOREIGN KEY(projection_id,human_key) REFERENCES crew_active_projection_member(projection_id,human_key),
 FOREIGN KEY(snapshot_id,expedition_id,person_id) REFERENCES crew_assignment_observation(snapshot_id,expedition_id,person_id),
 FOREIGN KEY(roster_id,member_index) REFERENCES crew_editorial_roster_member(roster_id,member_index),
 FOREIGN KEY(evidence_id,subject_index) REFERENCES crew_evidence_subject(evidence_id,subject_index),
 CHECK(NOT eligible OR (freshness='FRESH' AND departure_evidence_id IS NULL)),
 CHECK((support_type='LL2_ASSIGNMENT' AND snapshot_id IS NOT NULL AND expedition_id IS NOT NULL AND person_id IS NOT NULL AND roster_id IS NULL AND evidence_id IS NULL AND decision_id IS NULL)
    OR (support_type='NASA_EDITORIAL_ROSTER' AND roster_id IS NOT NULL AND member_index IS NOT NULL AND acquisition_id IS NOT NULL AND snapshot_id IS NULL AND evidence_id IS NULL AND decision_id IS NOT NULL AND observation_id IS NOT NULL)
    OR (support_type IN ('NASA_OPERATIONAL_POSITIVE','QUALIFIED_REENTRY') AND evidence_id IS NOT NULL AND subject_index IS NOT NULL AND snapshot_id IS NULL AND roster_id IS NULL AND decision_id IS NOT NULL AND observation_id IS NOT NULL))
);
CREATE TABLE crew_active_projection_slot (
 projection_id bigint NOT NULL REFERENCES crew_active_projection_revision(id), slot_key varchar(300) NOT NULL,
 state varchar(50) NOT NULL CHECK(state IN ('UNRESOLVED_ACTIVE_SOURCE_SLOT','RETAINED_SOURCE_SLOT','RETAINED_OPERATIONAL_SLOT')),
 acquisition_id bigint REFERENCES crew_editorial_acquisition(id), roster_id bigint, member_index integer,
 evidence_id bigint, subject_index integer, decision_id bigint REFERENCES crew_auto_decision_revision(id),
 observation_id bigint REFERENCES crew_auto_observation(id), payload jsonb NOT NULL,
 PRIMARY KEY(projection_id,slot_key),
 FOREIGN KEY(roster_id,member_index) REFERENCES crew_editorial_roster_member(roster_id,member_index),
 FOREIGN KEY(evidence_id,subject_index) REFERENCES crew_evidence_subject(evidence_id,subject_index),
 CHECK((roster_id IS NOT NULL AND member_index IS NOT NULL AND acquisition_id IS NOT NULL AND evidence_id IS NULL AND subject_index IS NULL)
   OR (evidence_id IS NOT NULL AND subject_index IS NOT NULL AND roster_id IS NULL AND member_index IS NULL)),
 CHECK(payload->'slot'->>'human' IS NULL)
);
CREATE TABLE crew_active_projection_finding (
 projection_id bigint NOT NULL REFERENCES crew_active_projection_revision(id),
 namespace varchar(30) NOT NULL CHECK(namespace IN ('MEMBERSHIP','COUNT','SOURCE_FIELD','SOURCE_HEALTH','IDENTITY')),
 code varchar(150) NOT NULL, subject varchar(500) NOT NULL, detail varchar(1000) NOT NULL,
 PRIMARY KEY(projection_id,namespace,code,subject,detail)
);
CREATE TABLE crew_active_projection_evidence (
 projection_id bigint NOT NULL REFERENCES crew_active_projection_revision(id),
 evidence_id bigint NOT NULL REFERENCES crew_verification_evidence(id),
 document_id bigint NOT NULL REFERENCES crew_source_document(id),
 PRIMARY KEY(projection_id,evidence_id)
);
-- Notifications are generation-safe, transactionally coalesced. Scheduler is the expiry safety net.
CREATE TABLE crew_active_projection_work (
 singleton boolean PRIMARY KEY CHECK(singleton), generation bigint NOT NULL CHECK(generation>0),
 completed_generation bigint NOT NULL CHECK(completed_generation>=0 AND completed_generation<=generation),
 notified_at timestamptz NOT NULL, last_success_at timestamptz, failures bigint NOT NULL DEFAULT 0 CHECK(failures>=0)
);
INSERT INTO crew_active_projection_work VALUES(true,1,0,now(),NULL,0);
CREATE FUNCTION crew_active_notify() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE crew_active_projection_work SET generation=generation+1,notified_at=now() WHERE singleton;
 RETURN NULL;
END $$;
CREATE TRIGGER crew_active_run_change AFTER INSERT OR UPDATE ON crew_source_sync_run FOR EACH STATEMENT EXECUTE FUNCTION crew_active_notify();
