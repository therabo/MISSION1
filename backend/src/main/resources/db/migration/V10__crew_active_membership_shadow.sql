CREATE FUNCTION crew_active_check_revision() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE pin record;
BEGIN
 FOR pin IN SELECT * FROM (VALUES
  ('ll2_run_id','ll2Run'),('ll2_snapshot_id','ll2Snapshot'),
  ('roster_acquisition_id','rosterAcquisition'),('roster_id','roster'),
  ('topic_acquisition_id','topicAcquisition'),('topic_count_fact_id','topicCountFact'),
  ('graph_id','graph'),('operational_run_id','operationalRun'),('operational_attempt_id','operationalAttempt')
 ) fields(column_name,cut_key) LOOP
  IF to_jsonb(NEW)->pin.column_name IS DISTINCT FROM NEW.input_cut->pin.cut_key THEN
   RAISE EXCEPTION 'Serialized and relational input cut disagree' USING ERRCODE='23514';
  END IF;
 END LOOP;
 PERFORM pg_advisory_xact_lock(73491,6);
 IF NEW.predecessor_id IS DISTINCT FROM (SELECT id FROM crew_active_projection_revision ORDER BY id DESC LIMIT 1) THEN
  RAISE EXCEPTION 'Shadow projection predecessor is not current' USING ERRCODE='23514';
 END IF;
 IF NEW.ll2_run_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_source_sync_run r WHERE r.id=NEW.ll2_run_id AND r.source='LAUNCH_LIBRARY_2' AND r.completed_at<=NEW.evaluated_at AND r.snapshot_id IS NOT DISTINCT FROM NEW.ll2_snapshot_id AND (r.result_state='SUCCESS' OR r.source_state='NO_ACTIVE_EXPEDITION')) THEN
  RAISE EXCEPTION 'Wrong LL2 input cut' USING ERRCODE='23514';
 END IF;
 IF NEW.roster_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_editorial_acquisition a WHERE a.id=NEW.roster_acquisition_id AND a.roster_id=NEW.roster_id AND a.outcome<>'FAILURE' AND a.completed_at<=NEW.evaluated_at) THEN
  RAISE EXCEPTION 'Wrong editorial input cut' USING ERRCODE='23514';
 END IF;
 IF NEW.topic_acquisition_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_editorial_acquisition a WHERE a.id=NEW.topic_acquisition_id AND a.stream='NASA_EDITORIAL_TOPIC' AND a.completed_at<=NEW.evaluated_at AND a.outcome<>'FAILURE') THEN
  RAISE EXCEPTION 'Wrong topic input cut' USING ERRCODE='23514';
 END IF;
 IF NEW.topic_count_fact_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_editorial_fact_capture f WHERE f.acquisition_id=NEW.topic_acquisition_id AND f.fact_id=NEW.topic_count_fact_id) THEN
  RAISE EXCEPTION 'Wrong topic fact lineage' USING ERRCODE='23514';
 END IF;
 IF NEW.graph_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_auto_graph_revision g WHERE g.id=NEW.graph_id AND g.applied_at<=NEW.evaluated_at) THEN
  RAISE EXCEPTION 'Future identity graph' USING ERRCODE='23514';
 END IF;
 IF NEW.operational_attempt_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_source_sync_run r WHERE r.id=NEW.operational_attempt_id AND r.source='NASA_OFFICIAL' AND r.completed_at<=NEW.evaluated_at) THEN
  RAISE EXCEPTION 'Wrong operational health cut' USING ERRCODE='23514';
 END IF;
 IF NEW.operational_run_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_source_sync_run r WHERE r.id=NEW.operational_run_id AND r.source='NASA_OFFICIAL' AND r.result_state='SUCCESS' AND r.completed_at<=NEW.evaluated_at) THEN
  RAISE EXCEPTION 'Wrong operational success cut' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_active_revision_lineage BEFORE INSERT ON crew_active_projection_revision FOR EACH ROW EXECUTE FUNCTION crew_active_check_revision();
CREATE FUNCTION crew_active_check_support() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p crew_active_projection_revision; m crew_active_projection_member;
BEGIN
 SELECT * INTO p FROM crew_active_projection_revision WHERE id=NEW.projection_id;
 SELECT * INTO m FROM crew_active_projection_member WHERE projection_id=NEW.projection_id AND human_key=NEW.human_key;
 IF NEW.snapshot_id IS NOT NULL AND (NEW.snapshot_id IS DISTINCT FROM p.ll2_snapshot_id OR NEW.person_id IS DISTINCT FROM m.person_id) THEN
  RAISE EXCEPTION 'Wrong assignment owner/cut' USING ERRCODE='23514';
 END IF;
 IF NEW.roster_id IS NOT NULL AND (NEW.roster_id IS DISTINCT FROM p.roster_id OR NEW.acquisition_id IS DISTINCT FROM p.roster_acquisition_id) THEN
  RAISE EXCEPTION 'Wrong roster owner/cut' USING ERRCODE='23514';
 END IF;
 IF NEW.evidence_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_active_projection_evidence e WHERE e.projection_id=NEW.projection_id AND e.evidence_id=NEW.evidence_id) THEN
  RAISE EXCEPTION 'Operational support outside pinned evidence cut' USING ERRCODE='23514';
 END IF;
 IF NEW.departure_evidence_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_active_projection_evidence pe JOIN crew_verification_evidence e ON e.id=pe.evidence_id WHERE pe.projection_id=NEW.projection_id AND e.id=NEW.departure_evidence_id AND e.evidence_type='PERSON_DEPARTED_STATION' AND e.assertion='COMPLETED') THEN
  RAISE EXCEPTION 'Unqualified completed departure veto' USING ERRCODE='23514';
 END IF;
 IF NEW.decision_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_auto_graph_application ga JOIN crew_auto_decision_revision d ON d.id=ga.decision_id JOIN crew_auto_candidate c ON c.id=d.candidate_id JOIN crew_auto_feature_snapshot f ON f.snapshot_hash=d.snapshot_hash WHERE ga.graph_id=p.graph_id AND d.id=NEW.decision_id AND d.outcome='AUTO_MATCH' AND c.candidate_key=NEW.human_key AND f.source_observation_id=NEW.observation_id) THEN
  RAISE EXCEPTION 'Unqualified automatic binding' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_active_support_lineage BEFORE INSERT ON crew_active_projection_support FOR EACH ROW EXECUTE FUNCTION crew_active_check_support();
CREATE FUNCTION crew_active_check_slot() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.evidence_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_active_projection_evidence e WHERE e.projection_id=NEW.projection_id AND e.evidence_id=NEW.evidence_id) THEN
  RAISE EXCEPTION 'Unresolved operational slot outside pinned evidence cut' USING ERRCODE='23514';
 END IF;
 IF NEW.roster_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_active_projection_revision p WHERE p.id=NEW.projection_id AND p.roster_id=NEW.roster_id AND p.roster_acquisition_id=NEW.acquisition_id) THEN
  RAISE EXCEPTION 'Wrong unresolved roster cut' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_active_slot_lineage BEFORE INSERT ON crew_active_projection_slot FOR EACH ROW EXECUTE FUNCTION crew_active_check_slot();
