-- ADR-0020. S10 has no production consumer. Existing V1-V10 rows/definitions are untouched.
CREATE TABLE crew_operational_binding_release (
 version varchar(100) PRIMARY KEY, installed_at timestamptz NOT NULL,
 serialized_policy text NOT NULL, policy jsonb NOT NULL CHECK(policy=serialized_policy::jsonb),
 policy_hash varchar(64) NOT NULL CHECK(policy_hash=encode(sha256(convert_to(serialized_policy,'UTF8')),'hex')),
 model_sha varchar(64) NOT NULL CHECK(model_sha ~ '^[0-9a-f]{64}$')
);
CREATE TABLE crew_operational_resource_version (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 requested_url varchar(2000) NOT NULL, final_url varchar(2000) NOT NULL,
 redirects jsonb NOT NULL CHECK(jsonb_typeof(redirects)='array' AND jsonb_array_length(redirects)<=5),
 captured_at timestamptz NOT NULL, http_status integer NOT NULL CHECK(http_status BETWEEN 200 AND 299),
 content_type varchar(200) NOT NULL, body_hash varchar(64) NOT NULL CHECK(body_hash ~ '^[0-9a-f]{64}$'),
 body bytea NOT NULL CHECK(octet_length(body) BETWEEN 1 AND 2097152), parser_version varchar(100) NOT NULL,
 facts jsonb NOT NULL CHECK(jsonb_typeof(facts)='array'),
 CHECK(body_hash=encode(sha256(body),'hex')),
 UNIQUE(requested_url,body_hash,parser_version)
);
CREATE TABLE crew_operational_resource_attempt (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, requested_url varchar(2000) NOT NULL,
 attempted_at timestamptz NOT NULL, completed_at timestamptz NOT NULL CHECK(completed_at>=attempted_at),
 http_status integer, reason varchar(100) NOT NULL,
 retry_at timestamptz,
 resource_version_id bigint REFERENCES crew_operational_resource_version(id),
 reused_editorial_acquisition_id bigint REFERENCES crew_editorial_acquisition(id),
 CHECK(NOT(resource_version_id IS NOT NULL AND reused_editorial_acquisition_id IS NOT NULL))
);
CREATE INDEX crew_operational_resource_validation_idx ON crew_operational_resource_attempt(resource_version_id,completed_at DESC,id DESC);
CREATE INDEX crew_operational_resource_attempt_url_idx ON crew_operational_resource_attempt(requested_url,completed_at DESC,id DESC);
CREATE TABLE crew_operational_resource_work (
 requested_url varchar(2000) PRIMARY KEY, next_at timestamptz NOT NULL,
 claimed_until timestamptz NOT NULL DEFAULT 'epoch', claim_token uuid,
 failures integer NOT NULL DEFAULT 0 CHECK(failures>=0), discovered_at timestamptz NOT NULL
);
CREATE TABLE crew_operational_request_permit (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 host varchar(100) NOT NULL, reserved_at timestamptz NOT NULL
);
CREATE INDEX crew_operational_request_host_idx ON crew_operational_request_permit(host,reserved_at DESC);
CREATE TABLE crew_operational_binding_work (
 singleton boolean PRIMARY KEY CHECK(singleton), generation bigint NOT NULL CHECK(generation>0),
 completed_generation bigint NOT NULL CHECK(completed_generation>=0 AND completed_generation<=generation),
 notified_at timestamptz NOT NULL, next_at timestamptz NOT NULL, claimed_until timestamptz NOT NULL,
 claim_token uuid, failures integer NOT NULL DEFAULT 0 CHECK(failures>=0)
);
INSERT INTO crew_operational_binding_work VALUES(true,1,0,now(),'epoch','epoch',NULL,0);
CREATE TABLE crew_operational_binding_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, binding_key varchar(64) NOT NULL CHECK(binding_key ~ '^[0-9a-f]{64}$'),
 subject_key varchar(240) NOT NULL, source_version varchar(64) NOT NULL CHECK(source_version ~ '^[0-9a-f]{64}$'),
 evidence_id bigint NOT NULL, subject_index integer NOT NULL, document_id bigint NOT NULL REFERENCES crew_source_document(id),
 evidence_hash varchar(64) NOT NULL, document_hash varchar(64) NOT NULL,
 predecessor_id bigint REFERENCES crew_operational_binding_revision(id),
 release_version varchar(100) NOT NULL REFERENCES crew_operational_binding_release(version),
 input_hash varchar(64) NOT NULL, serialized_cut text NOT NULL, input_cut jsonb NOT NULL CHECK(input_cut=serialized_cut::jsonb),
 known_at timestamptz NOT NULL, effective_at timestamptz,
 outcome varchar(20) NOT NULL CHECK(outcome IN ('AUTO_MATCH','AUTO_DEFER','CONFLICT','SUPERSEDED')),
 target_provider_key varchar(240), target_person_id uuid REFERENCES crew_person(id),
 probability double precision NOT NULL CHECK(probability BETWEEN 0 AND 1),
 runner_key varchar(240), runner_probability double precision NOT NULL CHECK(runner_probability BETWEEN 0 AND 1),
 margin double precision NOT NULL CHECK(margin BETWEEN 0 AND 1),
 reasons jsonb NOT NULL CHECK(jsonb_typeof(reasons)='array'), correction_reason varchar(100) NOT NULL,
 serialized_result text NOT NULL, result jsonb NOT NULL CHECK(result=serialized_result::jsonb),
 result_hash varchar(64) NOT NULL,
 production_person_id uuid REFERENCES crew_person(id), production_resolution_id bigint REFERENCES crew_identity_resolution(id),
 production_projection_id bigint REFERENCES crew_active_projection_revision(id), comparison varchar(80) NOT NULL,
 consequences jsonb NOT NULL CHECK(jsonb_typeof(consequences)='array'),
 FOREIGN KEY(evidence_id,subject_index) REFERENCES crew_evidence_subject(evidence_id,subject_index),
 CHECK(input_hash=encode(sha256(convert_to(serialized_cut,'UTF8')),'hex')),
 CHECK(result_hash=encode(sha256(convert_to(serialized_result,'UTF8')),'hex')),
 CHECK(binding_key=encode(sha256(convert_to(subject_key||':'||source_version||':'||evidence_hash,'UTF8')),'hex')),
 CHECK(input_cut->'subject'->>'key'=subject_key AND input_cut->'subject'->>'version'=source_version
   AND input_cut->'subject'->>'evidenceHash'=evidence_hash AND input_cut->'subject'->>'documentHash'=document_hash),
 CHECK(coalesce(result->'evaluation'->>'outcome'=outcome,false)),
 CHECK((outcome='AUTO_MATCH')=(target_person_id IS NOT NULL)),
 CHECK((target_person_id IS NULL)=(target_provider_key IS NULL)),
 CHECK(target_provider_key IS NULL OR target_provider_key LIKE 'LL2:PERSON:%'),
 UNIQUE(predecessor_id), UNIQUE(id,binding_key)
);
CREATE INDEX crew_operational_binding_latest_idx ON crew_operational_binding_revision(binding_key,id DESC);
CREATE TABLE crew_operational_binding_candidate (
 revision_id bigint NOT NULL REFERENCES crew_operational_binding_revision(id), candidate_key varchar(240) NOT NULL,
 candidate_rank integer NOT NULL CHECK(candidate_rank BETWEEN 0 AND 255), payload jsonb NOT NULL,
 PRIMARY KEY(revision_id,candidate_key), UNIQUE(revision_id,candidate_rank)
);
CREATE TABLE crew_operational_binding_proof (
 revision_id bigint NOT NULL REFERENCES crew_operational_binding_revision(id), proof_index integer NOT NULL CHECK(proof_index>=0),
 candidate_key varchar(240) NOT NULL, resource_ref varchar(300) NOT NULL, resource_hash varchar(64) NOT NULL CHECK(resource_hash ~ '^[0-9a-f]{64}$'),
 authority varchar(100) NOT NULL, relation_type varchar(300) NOT NULL, independence_group varchar(100) NOT NULL,
 required boolean NOT NULL, payload jsonb NOT NULL,
 PRIMARY KEY(revision_id,proof_index), UNIQUE(revision_id,candidate_key,resource_ref,resource_hash,authority,relation_type), FOREIGN KEY(revision_id,candidate_key) REFERENCES crew_operational_binding_candidate(revision_id,candidate_key)
);
CREATE FUNCTION crew_operational_binding_notify() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE crew_operational_binding_work SET generation=generation+1,notified_at=now(),next_at=least(next_at,now()) WHERE singleton;
 RETURN NULL;
END $$;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['crew_subject_version_link','crew_source_sync_run','crew_editorial_acquisition',
  'crew_person_observation','crew_identity_binding_version','crew_person_equivalence_decision',
  'crew_operational_resource_version','crew_operational_resource_attempt','crew_operational_binding_release'] LOOP
  EXECUTE format('CREATE TRIGGER %I AFTER INSERT ON %I FOR EACH STATEMENT EXECUTE FUNCTION crew_operational_binding_notify()',t||'_s10_notify',t);
 END LOOP;
END $$;
CREATE FUNCTION crew_operational_binding_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(73491,10);
 IF NEW.predecessor_id IS DISTINCT FROM (SELECT id FROM crew_operational_binding_revision WHERE binding_key=NEW.binding_key ORDER BY id DESC LIMIT 1) THEN
  RAISE EXCEPTION 'S10 predecessor is not current' USING ERRCODE='23514';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM crew_verification_evidence e JOIN crew_source_document d ON d.id=NEW.document_id
   JOIN crew_document_evidence de ON de.document_id=d.id AND de.evidence_id=e.id
   WHERE e.id=NEW.evidence_id AND e.evidence_hash=NEW.evidence_hash AND d.content_hash=NEW.document_hash AND d.retrieved_at<=NEW.known_at) THEN
  RAISE EXCEPTION 'S10 exact source lineage mismatch' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM crew_subject_version_link v WHERE v.evidence_id=NEW.evidence_id AND v.subject_index=NEW.subject_index) THEN
  IF NOT EXISTS(SELECT 1 FROM crew_subject_version_link v WHERE v.evidence_id=NEW.evidence_id AND v.subject_index=NEW.subject_index
    AND v.subject_key=NEW.subject_key AND v.version_key=NEW.source_version) THEN
   RAISE EXCEPTION 'S10 subject version mismatch' USING ERRCODE='23514';
  END IF;
 ELSE
  IF NEW.subject_key<>'legacy:'||NEW.evidence_id||':'||NEW.subject_index OR NEW.source_version<>encode(sha256(convert_to(NEW.subject_key||':'||NEW.evidence_hash,'UTF8')),'hex') THEN
   RAISE EXCEPTION 'S10 legacy source key mismatch' USING ERRCODE='23514';
  END IF;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM crew_evidence_subject s WHERE s.evidence_id=NEW.evidence_id AND s.subject_index=NEW.subject_index
   AND s.display_name=NEW.input_cut->'subject'->>'name') THEN
  RAISE EXCEPTION 'S10 source mention mismatch' USING ERRCODE='23514';
 END IF;
 IF NEW.outcome='AUTO_MATCH' AND (
  jsonb_array_length(NEW.reasons)<>0 OR NEW.margin<(SELECT (policy->>'margin')::double precision FROM crew_operational_binding_release WHERE version=NEW.release_version)
  OR NEW.probability<(SELECT (policy->>CASE WHEN NEW.input_cut->'subject'->>'type'='PERSON_DEPARTED_STATION' THEN 'departure' ELSE 'observation' END)::double precision FROM crew_operational_binding_release WHERE version=NEW.release_version)
  OR NOT EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.result->'evaluation'->'candidates') c
    WHERE c->>'key'=NEW.target_provider_key AND (c->>'qualifiedWitness')::boolean
      AND (c->>'temporal')::boolean AND (c->>'compatibleName')::boolean
      AND jsonb_array_length(c->'contradictions')=0 AND jsonb_array_length(c->'proofs')>0)) THEN
  RAISE EXCEPTION 'S10 match lacks qualified policy gates' USING ERRCODE='23514';
 END IF;
 IF NEW.target_person_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_person_external_id x
   JOIN crew_person_observation o ON o.person_id=x.person_id AND o.source=x.source AND o.external_id=x.external_id
   WHERE x.source='LAUNCH_LIBRARY_2' AND 'LL2:PERSON:'||x.external_id=NEW.target_provider_key
   AND (x.person_id=NEW.target_person_id OR EXISTS(SELECT 1 FROM crew_person_equivalence_decision q
     WHERE q.alias_id=x.person_id AND q.representative_id=NEW.target_person_id AND q.status='ACTIVE' AND q.known_at<=NEW.known_at))) THEN
  RAISE EXCEPTION 'S10 target lacks existing publishable provider anchor' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_operational_binding_lineage BEFORE INSERT ON crew_operational_binding_revision FOR EACH ROW EXECUTE FUNCTION crew_operational_binding_check();
CREATE FUNCTION crew_operational_resource_check() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF jsonb_array_length(NEW.facts)<1 OR EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.facts) f
   WHERE f->>'hash' IS DISTINCT FROM NEW.body_hash OR f->>'url' IS DISTINCT FROM NEW.requested_url OR f->>'finalUrl' IS DISTINCT FROM NEW.final_url
    OR (f->>'capturedAt')::timestamptz IS DISTINCT FROM NEW.captured_at OR f->'redirects' IS DISTINCT FROM NEW.redirects) THEN
  RAISE EXCEPTION 'S10 resource fact capture mismatch' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_operational_resource_lineage BEFORE INSERT ON crew_operational_resource_version FOR EACH ROW EXECUTE FUNCTION crew_operational_resource_check();
CREATE FUNCTION crew_operational_binding_open() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM crew_operational_binding_revision r WHERE r.id=NEW.revision_id
   AND r.xmin::text::numeric=mod(pg_current_xact_id()::text::numeric,4294967296)) THEN
  RAISE EXCEPTION 'S10 binding revision sealed' USING ERRCODE='23514';
 END IF;
 IF TG_TABLE_NAME='crew_operational_binding_proof' THEN
  IF NOT EXISTS(SELECT 1 FROM crew_operational_resource_version v WHERE v.body_hash=NEW.resource_hash
    AND v.captured_at<=(SELECT known_at FROM crew_operational_binding_revision WHERE id=NEW.revision_id))
   AND NOT EXISTS(SELECT 1 FROM crew_editorial_acquisition a JOIN crew_source_document d ON d.id=a.document_id
    WHERE a.stream='NASA_PERSON_RESOURCE' AND a.outcome<>'FAILURE' AND d.content_hash=NEW.resource_hash
      AND a.completed_at<=(SELECT known_at FROM crew_operational_binding_revision WHERE id=NEW.revision_id)) THEN
   RAISE EXCEPTION 'S10 proof has no retained official capture' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_operational_candidate_sealed BEFORE INSERT ON crew_operational_binding_candidate FOR EACH ROW EXECUTE FUNCTION crew_operational_binding_open();
CREATE TRIGGER crew_operational_proof_sealed BEFORE INSERT ON crew_operational_binding_proof FOR EACH ROW EXECUTE FUNCTION crew_operational_binding_open();
CREATE FUNCTION crew_operational_binding_complete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (SELECT count(*) FROM crew_operational_binding_candidate WHERE revision_id=NEW.id)
     <>jsonb_array_length(NEW.result->'evaluation'->'candidates')
 OR EXISTS(SELECT 1 FROM crew_operational_binding_candidate c WHERE c.revision_id=NEW.id
   AND c.payload<>NEW.result->'evaluation'->'candidates'->c.candidate_rank)
 OR EXISTS(SELECT 1 FROM crew_operational_binding_proof p JOIN crew_operational_binding_candidate c
   ON c.revision_id=p.revision_id AND c.candidate_key=p.candidate_key WHERE p.revision_id=NEW.id
   AND NOT c.payload->'proofs' @> jsonb_build_array(p.payload))
 OR (SELECT count(*) FROM crew_operational_binding_proof WHERE revision_id=NEW.id)
   <>(SELECT coalesce(sum(jsonb_array_length(c.payload->'proofs')),0) FROM crew_operational_binding_candidate c WHERE c.revision_id=NEW.id) THEN
  RAISE EXCEPTION 'S10 incomplete candidate or proof lineage' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE CONSTRAINT TRIGGER crew_operational_binding_atomic AFTER INSERT ON crew_operational_binding_revision
 DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION crew_operational_binding_complete();
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['crew_operational_binding_release','crew_operational_resource_version','crew_operational_resource_attempt',
  'crew_operational_binding_revision','crew_operational_binding_candidate','crew_operational_binding_proof','crew_operational_request_permit'] LOOP
  EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation()',t||'_immutable',t);
 END LOOP;
END $$;
