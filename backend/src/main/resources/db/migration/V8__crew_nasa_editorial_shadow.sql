-- ADR-0014. Additive shadow source only. No legacy data/constraints/selectors are changed.
CREATE TABLE crew_editorial_resource (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_kind varchar(40) NOT NULL CHECK(resource_kind IN ('NASA_TOPIC','NASA_MISSION','NASA_PEOPLE_RESOURCE','NASA_MISSION_STATUS','NASA_MISSION_TARGET')),
 wp_id bigint NOT NULL CHECK(wp_id>0),
 UNIQUE(resource_kind,wp_id), UNIQUE(id,resource_kind)
);
CREATE TABLE crew_editorial_roster_version (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_id bigint NOT NULL,
 resource_kind varchar(40) NOT NULL DEFAULT 'NASA_MISSION' CHECK(resource_kind='NASA_MISSION'),
 expedition_number integer NOT NULL CHECK(expedition_number BETWEEN 1 AND 999),
 semantic_hash varchar(64) NOT NULL CHECK(semantic_hash ~ '^[0-9a-f]{64}$'),
 parser_name varchar(100) NOT NULL CHECK(length(parser_name)>0),
 parser_version varchar(40) NOT NULL CHECK(length(parser_version)>0),
 completeness varchar(40) NOT NULL CHECK(completeness='PARSED_EDITORIAL_SECTION'),
 conflicts jsonb NOT NULL CHECK(jsonb_typeof(conflicts)='array'),
 FOREIGN KEY(resource_id,resource_kind) REFERENCES crew_editorial_resource(id,resource_kind),
 UNIQUE(resource_id,semantic_hash,parser_name,parser_version), UNIQUE(id,resource_id)
);
CREATE TABLE crew_editorial_roster_member (
 roster_id bigint NOT NULL REFERENCES crew_editorial_roster_version(id),
 member_index integer NOT NULL CHECK(member_index BETWEEN 0 AND 29),
 resource_kind varchar(40) NOT NULL DEFAULT 'NASA_EXPEDITION_ROSTER_SLOT' CHECK(resource_kind='NASA_EXPEDITION_ROSTER_SLOT'),
 display_name varchar(200) NOT NULL CHECK(length(display_name)>0),
 role_text varchar(1000) NOT NULL, agency_text varchar(200),
 mentions jsonb NOT NULL CHECK(jsonb_typeof(mentions)='array' AND jsonb_array_length(mentions) BETWEEN 1 AND 2),
 conflicts jsonb NOT NULL CHECK(jsonb_typeof(conflicts)='array'),
 semantic_hash varchar(64) NOT NULL CHECK(semantic_hash ~ '^[0-9a-f]{64}$'),
 PRIMARY KEY(roster_id,member_index), UNIQUE(roster_id,display_name)
);
CREATE TABLE crew_editorial_acquisition (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 stream varchar(40) NOT NULL CHECK(stream IN ('NASA_EDITORIAL_TOPIC','NASA_EDITORIAL_EXPEDITION','NASA_PERSON_RESOURCE')),
 requested_url varchar(2000) NOT NULL, final_url varchar(2000) NOT NULL,
 redirects jsonb NOT NULL CHECK(jsonb_typeof(redirects)='array' AND jsonb_array_length(redirects)<=5),
 started_at timestamptz NOT NULL, completed_at timestamptz NOT NULL CHECK(completed_at>=started_at),
 http_status integer CHECK(http_status BETWEEN 100 AND 599), headers jsonb NOT NULL CHECK(jsonb_typeof(headers)='object'),
 document_id bigint REFERENCES crew_source_document(id), resource_id bigint REFERENCES crew_editorial_resource(id),
 resource_metadata jsonb CHECK(jsonb_typeof(resource_metadata)='object'),
 outcome varchar(20) NOT NULL CHECK(outcome IN ('SUCCESS','DEGRADED','FAILURE')),
 reason varchar(200) NOT NULL CHECK(length(reason)>0), retry_after_at timestamptz,
 roster_id bigint, FOREIGN KEY(roster_id,resource_id) REFERENCES crew_editorial_roster_version(id,resource_id),
 CHECK(roster_id IS NULL OR (stream='NASA_EDITORIAL_EXPEDITION' AND outcome<>'FAILURE' AND document_id IS NOT NULL)),
 CHECK(outcome='FAILURE' OR document_id IS NOT NULL),
 parser_name varchar(100) NOT NULL CHECK(length(parser_name)>0), parser_version varchar(40) NOT NULL CHECK(length(parser_version)>0)
);
CREATE INDEX crew_editorial_latest_idx ON crew_editorial_acquisition(stream,completed_at DESC,id DESC);
CREATE INDEX crew_editorial_url_idx ON crew_editorial_acquisition(stream,requested_url,completed_at DESC,id DESC);
CREATE INDEX crew_editorial_roster_capture_idx ON crew_editorial_acquisition(completed_at DESC,id DESC) WHERE roster_id IS NOT NULL;
CREATE TABLE crew_editorial_topic_fact (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 resource_id bigint NOT NULL,
 resource_kind varchar(40) NOT NULL DEFAULT 'NASA_TOPIC' CHECK(resource_kind='NASA_TOPIC'),
 fact_kind varchar(80) NOT NULL CHECK(fact_kind IN ('NASA_EDITORIAL_EXPEDITION_NUMBER','NASA_WEBSITE_EDITORIAL_REPORTED_ABOARD_COUNT')),
 value integer NOT NULL CHECK(value>=0), unit varchar(20) NOT NULL CHECK(unit IN ('number','persons')),
 source_text varchar(1000) NOT NULL, source_locator varchar(1000) NOT NULL,
 semantic_hash varchar(64) NOT NULL CHECK(semantic_hash ~ '^[0-9a-f]{64}$'),
 parser_name varchar(100) NOT NULL CHECK(length(parser_name)>0), parser_version varchar(40) NOT NULL CHECK(length(parser_version)>0),
 FOREIGN KEY(resource_id,resource_kind) REFERENCES crew_editorial_resource(id,resource_kind),
 CHECK((fact_kind='NASA_EDITORIAL_EXPEDITION_NUMBER' AND value BETWEEN 1 AND 999 AND unit='number') OR (fact_kind='NASA_WEBSITE_EDITORIAL_REPORTED_ABOARD_COUNT' AND value<=100 AND unit='persons')),
 UNIQUE(resource_id,fact_kind,semantic_hash,parser_name,parser_version), UNIQUE(id,resource_id)
);
CREATE TABLE crew_editorial_fact_capture (
 acquisition_id bigint NOT NULL REFERENCES crew_editorial_acquisition(id),
 fact_id bigint NOT NULL REFERENCES crew_editorial_topic_fact(id), PRIMARY KEY(acquisition_id,fact_id)
);
CREATE TABLE crew_editorial_resource_relation (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 roster_id bigint NOT NULL, member_index integer NOT NULL,
 subject_name varchar(200) NOT NULL, observed_url varchar(2000) NOT NULL, source_locator varchar(1000) NOT NULL,
 status varchar(50) NOT NULL CHECK(status IN ('OBSERVED_LINK','VERIFIED_ABOUT_PERSON_RELATION','REJECTED_MISMATCH')),
 target_resource_id bigint REFERENCES crew_editorial_resource(id), acquisition_id bigint REFERENCES crew_editorial_acquisition(id),
 reason varchar(200) NOT NULL, relation_hash varchar(64) NOT NULL UNIQUE CHECK(relation_hash ~ '^[0-9a-f]{64}$'),
 FOREIGN KEY(roster_id,member_index) REFERENCES crew_editorial_roster_member(roster_id,member_index),
 CHECK(status<>'VERIFIED_ABOUT_PERSON_RELATION' OR (target_resource_id IS NOT NULL AND acquisition_id IS NOT NULL))
);
CREATE INDEX crew_editorial_relation_slot_idx ON crew_editorial_resource_relation(roster_id,member_index,id DESC);
CREATE FUNCTION crew_check_editorial_lineage() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_TABLE_NAME='crew_editorial_acquisition' THEN
  IF NEW.document_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_source_document d WHERE d.id=NEW.document_id
      AND d.source_type=NEW.stream AND d.source_url=NEW.requested_url AND d.parser_name=NEW.parser_name AND d.parser_version=NEW.parser_version) THEN
   RAISE EXCEPTION 'Editorial document ownership mismatch' USING ERRCODE='23514';
  END IF;
  IF NEW.resource_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_editorial_resource r WHERE r.id=NEW.resource_id
      AND r.resource_kind=NEW.resource_metadata->>'kind' AND r.wp_id=(NEW.resource_metadata->>'wpId')::bigint) THEN
   RAISE EXCEPTION 'Editorial typed resource metadata mismatch' USING ERRCODE='23514';
  END IF;
 ELSIF TG_TABLE_NAME='crew_editorial_fact_capture' THEN
  IF NOT EXISTS(SELECT 1 FROM crew_editorial_acquisition a JOIN crew_editorial_topic_fact f ON f.resource_id=a.resource_id
      WHERE a.id=NEW.acquisition_id AND f.id=NEW.fact_id AND a.stream='NASA_EDITORIAL_TOPIC') THEN
   RAISE EXCEPTION 'Editorial fact capture ownership mismatch' USING ERRCODE='23514';
  END IF;
 ELSE
  IF NOT EXISTS(SELECT 1 FROM crew_editorial_roster_member m WHERE m.roster_id=NEW.roster_id AND m.member_index=NEW.member_index AND m.display_name=NEW.subject_name) THEN
   RAISE EXCEPTION 'Editorial relation subject mismatch' USING ERRCODE='23514';
  END IF;
  IF NEW.target_resource_id IS NOT NULL AND NEW.acquisition_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_editorial_acquisition a
      JOIN crew_editorial_resource r ON r.id=a.resource_id WHERE a.id=NEW.acquisition_id AND a.resource_id=NEW.target_resource_id
      AND a.stream='NASA_PERSON_RESOURCE' AND r.resource_kind IN ('NASA_TOPIC','NASA_PEOPLE_RESOURCE') AND a.outcome<>'FAILURE') THEN
   RAISE EXCEPTION 'Editorial relation target ownership mismatch' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_editorial_capture_lineage BEFORE INSERT ON crew_editorial_acquisition FOR EACH ROW EXECUTE FUNCTION crew_check_editorial_lineage();
CREATE TRIGGER crew_editorial_fact_lineage BEFORE INSERT ON crew_editorial_fact_capture FOR EACH ROW EXECUTE FUNCTION crew_check_editorial_lineage();
CREATE TRIGGER crew_editorial_relation_lineage BEFORE INSERT ON crew_editorial_resource_relation FOR EACH ROW EXECUTE FUNCTION crew_check_editorial_lineage();
