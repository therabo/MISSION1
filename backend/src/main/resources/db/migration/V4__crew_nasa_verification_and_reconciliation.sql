-- ADR-0009. NASA evidence and derived interpretations, without modifying LL2 observations or Orbit.
CREATE TABLE crew_document_body (
    content_hash varchar(64) PRIMARY KEY CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    body bytea NOT NULL CHECK (octet_length(body) BETWEEN 1 AND 2097152)
);
CREATE TABLE crew_source_document (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source varchar(40) NOT NULL CHECK (source = 'NASA_OFFICIAL'),
    source_type varchar(80) NOT NULL,
    source_url text NOT NULL,
    retrieved_at timestamptz NOT NULL,
    source_published_at timestamptz,
    http_status integer CHECK (http_status BETWEEN 100 AND 599),
    http_etag text,
    http_last_modified text,
    content_type text,
    content_hash varchar(64) NOT NULL REFERENCES crew_document_body(content_hash),
    parser_name varchar(100) NOT NULL,
    parser_version varchar(40) NOT NULL,
    parsed boolean NOT NULL,
    UNIQUE(source_url, content_hash, parser_name, parser_version)
);
CREATE INDEX crew_document_url_idx ON crew_source_document(source_url, parser_name, parser_version, retrieved_at DESC, id DESC);
ALTER TABLE crew_source_sync_run ADD COLUMN verification_document_id bigint REFERENCES crew_source_document(id);
-- Replace only the V3 success/snapshot equivalence, retaining its LL2 semantics.
DO $$ DECLARE c record; BEGIN
    FOR c IN SELECT conname FROM pg_constraint WHERE conrelid = 'crew_source_sync_run'::regclass
        AND contype = 'c' AND pg_get_constraintdef(oid) LIKE '%SUCCESS%snapshot_id IS NOT NULL%'
    LOOP EXECUTE format('ALTER TABLE crew_source_sync_run DROP CONSTRAINT %I', c.conname); END LOOP;
END $$;
ALTER TABLE crew_source_sync_run ADD CONSTRAINT crew_source_success_input CHECK (
    (snapshot_id IS NULL OR (result_state = 'SUCCESS' AND source = 'LAUNCH_LIBRARY_2'))
    AND (verification_document_id IS NULL OR source = 'NASA_OFFICIAL')
    AND (result_state <> 'SUCCESS' OR
        (source = 'LAUNCH_LIBRARY_2' AND snapshot_id IS NOT NULL AND verification_document_id IS NULL)
        OR (source = 'NASA_OFFICIAL' AND verification_document_id IS NOT NULL AND snapshot_id IS NULL))
);
CREATE TABLE crew_verification_evidence (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL REFERENCES crew_source_document(id),
    evidence_hash varchar(64) NOT NULL UNIQUE CHECK (evidence_hash ~ '^[0-9a-f]{64}$'),
    station varchar(16) NOT NULL CHECK (station = 'ISS'),
    evidence_type varchar(50) NOT NULL CHECK (evidence_type IN ('PERSON_ENTERED_STATION','PERSON_DEPARTED_STATION',
        'PERSON_CURRENTLY_ABOARD','CREW_COUNT_ABOARD','EXPEDITION_MEMBERSHIP','DOCKING_OCCURRED','UNDOCKING_OCCURRED','HATCH_OPENED')),
    assertion varchar(20) NOT NULL CHECK (assertion IN ('OBSERVED','COMPLETED','PLANNED')),
    completeness varchar(20) NOT NULL CHECK (completeness IN ('EXHAUSTIVE','PARTIAL','EVENT_ONLY','COUNT_ONLY')),
    source_type varchar(80) NOT NULL,
    assertion_url text NOT NULL,
    source_published_at timestamptz,
    source_event_at timestamptz,
    supporting_excerpt text NOT NULL CHECK(length(supporting_excerpt)>0),
    parser_name varchar(100) NOT NULL,
    parser_version varchar(40) NOT NULL,
    evidence_method varchar(150) NOT NULL,
    crew_count integer CHECK(crew_count >= 0),
    CHECK ((evidence_type = 'CREW_COUNT_ABOARD') = (crew_count IS NOT NULL))
);
CREATE INDEX crew_evidence_time_idx ON crew_verification_evidence(station, source_published_at DESC, source_event_at DESC);
CREATE TABLE crew_evidence_subject (
    evidence_id bigint NOT NULL REFERENCES crew_verification_evidence(id),
    subject_index integer NOT NULL CHECK(subject_index>=0),
    display_name text NOT NULL CHECK(length(display_name)>0),
    official_profile_url text,
    external_ids jsonb NOT NULL CHECK(jsonb_typeof(external_ids)='array'),
    PRIMARY KEY(evidence_id,subject_index)
);
CREATE TABLE crew_document_evidence (
    document_id bigint NOT NULL REFERENCES crew_source_document(id),
    evidence_id bigint NOT NULL REFERENCES crew_verification_evidence(id),
    PRIMARY KEY(document_id,evidence_id)
);
CREATE TABLE crew_identity_resolution (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id bigint NOT NULL,
    subject_index integer NOT NULL,
    resolved_at timestamptz NOT NULL,
    person_id uuid REFERENCES crew_person(id),
    method varchar(40) NOT NULL CHECK(method IN ('EXTERNAL_ID','OFFICIAL_PROFILE','AUTHORITATIVE_MAPPING','EXACT_UNIQUE_NAME','UNRESOLVED','AMBIGUOUS')),
    candidates uuid[] NOT NULL,
    identity_key varchar(100),
    resolver_version varchar(80) NOT NULL,
    resolution_hash varchar(64) NOT NULL UNIQUE,
    FOREIGN KEY(evidence_id,subject_index) REFERENCES crew_evidence_subject(evidence_id,subject_index),
    CHECK((person_id IS NULL) = (method IN ('UNRESOLVED','AMBIGUOUS')))
);
CREATE INDEX crew_resolution_subject_idx ON crew_identity_resolution(evidence_id,subject_index,resolved_at DESC,id DESC);
CREATE TABLE crew_reconciliation_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    algorithm_version varchar(240) NOT NULL,
    result_state varchar(30) NOT NULL CHECK(result_state IN ('IN_PROGRESS','SUCCESS','FAILURE')),
    error_code varchar(80),
    snapshot_id bigint,
    CHECK((result_state='IN_PROGRESS')=(completed_at IS NULL)),
    CHECK(completed_at IS NULL OR completed_at >= started_at),
    CHECK((result_state='SUCCESS')=(snapshot_id IS NOT NULL))
);
CREATE TABLE crew_reconciliation_snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_key varchar(64) NOT NULL UNIQUE CHECK(state_key ~ '^[0-9a-f]{64}$'),
    algorithm_version varchar(240) NOT NULL,
    reconciliation_as_of timestamptz NOT NULL,
    primary_snapshot_id bigint REFERENCES crew_source_snapshot(id),
    primary_run_id bigint REFERENCES crew_source_sync_run(id),
    verification_run_id bigint REFERENCES crew_source_sync_run(id),
    primary_fetched_at timestamptz,
    verification_fetched_at timestamptz,
    status varchar(40) NOT NULL CHECK(status IN ('MATCH','NASA_AHEAD','LL2_AHEAD','PARTIAL_MATCH','PRIMARY_UNAVAILABLE','VERIFICATION_UNAVAILABLE','STALE','AMBIGUOUS')),
    official_crew_count integer CHECK(official_crew_count>=0),
    unidentified_count integer NOT NULL CHECK(unidentified_count>=0)
);
ALTER TABLE crew_reconciliation_run ADD FOREIGN KEY(snapshot_id) REFERENCES crew_reconciliation_snapshot(id);
CREATE INDEX crew_reconciliation_latest_idx ON crew_reconciliation_run(completed_at DESC,id DESC) WHERE result_state='SUCCESS';
CREATE TABLE crew_reconciliation_evidence (
    snapshot_id bigint NOT NULL REFERENCES crew_reconciliation_snapshot(id),
    evidence_id bigint NOT NULL REFERENCES crew_verification_evidence(id),
    PRIMARY KEY(snapshot_id,evidence_id)
);
CREATE TABLE crew_reconciliation_resolution (
    snapshot_id bigint NOT NULL REFERENCES crew_reconciliation_snapshot(id),
    resolution_id bigint NOT NULL REFERENCES crew_identity_resolution(id),
    PRIMARY KEY(snapshot_id,resolution_id)
);
CREATE TABLE crew_reconciled_person (
    snapshot_id bigint NOT NULL REFERENCES crew_reconciliation_snapshot(id),
    person_id uuid NOT NULL REFERENCES crew_person(id),
    presence varchar(40) NOT NULL CHECK(presence IN ('CONFIRMED_ABOARD','CONFIRMED_NOT_ABOARD','UNVERIFIED','UNKNOWN','STALE','AMBIGUOUS')),
    last_known_presence varchar(40),
    assertion_as_of timestamptz,
    ll2_assigned boolean NOT NULL,
    PRIMARY KEY(snapshot_id,person_id)
);
CREATE TABLE crew_reconciled_person_evidence (
    snapshot_id bigint NOT NULL,
    person_id uuid NOT NULL,
    evidence_id bigint NOT NULL,
    PRIMARY KEY(snapshot_id,person_id,evidence_id),
    FOREIGN KEY(snapshot_id,person_id) REFERENCES crew_reconciled_person(snapshot_id,person_id),
    FOREIGN KEY(snapshot_id,evidence_id) REFERENCES crew_reconciliation_evidence(snapshot_id,evidence_id)
);
DO $$ DECLARE t text; BEGIN
    FOREACH t IN ARRAY ARRAY['crew_document_body','crew_source_document','crew_verification_evidence',
        'crew_evidence_subject','crew_document_evidence','crew_identity_resolution','crew_reconciliation_snapshot',
        'crew_reconciliation_evidence','crew_reconciliation_resolution','crew_reconciled_person','crew_reconciled_person_evidence']
    LOOP EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation()',t||'_immutable',t); END LOOP;
END $$;
