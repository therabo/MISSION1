-- A source set is immutable; retrieval observations record repeat sightings of that set.
CREATE TABLE orbital_element_sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_number integer NOT NULL CHECK (catalog_number = 25544),
    source_format varchar(16) NOT NULL CHECK (source_format = 'TLE'),
    line1 varchar(69) NOT NULL CHECK (length(line1) = 69),
    line2 varchar(69) NOT NULL CHECK (length(line2) = 69),
    element_epoch timestamptz NOT NULL,
    provider varchar(100) NOT NULL CHECK (length(provider) > 0),
    upstream_origin varchar(100) NOT NULL CHECK (length(upstream_origin) > 0),
    source_uri varchar(2048) NOT NULL CHECK (length(source_uri) > 0),
    published_at timestamptz,
    sha256 varchar(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    classification varchar(64) NOT NULL
        CHECK (classification = 'SOURCE_PROVIDED_ORBITAL_ELEMENTS'),
    CONSTRAINT orbital_element_set_identity UNIQUE (provider, catalog_number, sha256)
);

CREATE INDEX orbital_element_sets_epoch_idx
    ON orbital_element_sets (element_epoch DESC, sha256);

CREATE TABLE orbital_element_observations (
    element_set_id bigint NOT NULL REFERENCES orbital_element_sets(id),
    retrieved_at timestamptz NOT NULL,
    PRIMARY KEY (element_set_id, retrieved_at)
);
