-- Crew source history only. ADR-0008. No changes to Orbit tables.
CREATE TABLE crew_source_snapshot (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source varchar(40) NOT NULL,
    station varchar(16) NOT NULL CHECK (station = 'ISS'),
    source_api_version varchar(80) NOT NULL,
    adapter_version varchar(80) NOT NULL,
    source_station_external_id varchar(100) NOT NULL CHECK (length(source_station_external_id) > 0),
    content_hash varchar(64) NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    first_observed_at timestamptz NOT NULL,
    source_url text NOT NULL,
    source_published_at timestamptz,
    source_event_at timestamptz,
    http_etag text,
    http_last_modified text,
    total_active_expeditions integer NOT NULL CHECK (total_active_expeditions = 1),
    candidates_complete boolean NOT NULL CHECK (candidates_complete),
    UNIQUE (source, station, source_station_external_id, source_api_version, adapter_version, content_hash),
    UNIQUE (id, source),
    UNIQUE (id, source, station)
);

CREATE TABLE crew_source_sync_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source varchar(40) NOT NULL,
    station varchar(16) NOT NULL CHECK (station = 'ISS'),
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    result_state varchar(40) NOT NULL CHECK (result_state IN ('IN_PROGRESS', 'SUCCESS', 'SOURCE_RESULT',
        'INVALID_SNAPSHOT', 'PERSISTENCE_FAILURE', 'UNEXPECTED_FAILURE',
        'SKIPPED_RATE_LIMIT', 'SKIPPED_NOT_DUE', 'SKIPPED_OVERLAP')),
    source_state varchar(40) CHECK (source_state IN ('AVAILABLE', 'NO_ACTIVE_EXPEDITION', 'SOURCE_UNAVAILABLE',
        'NOT_FOUND', 'RATE_LIMITED', 'MALFORMED_RESPONSE', 'STALE', 'AMBIGUOUS')),
    source_url text NOT NULL,
    http_status integer CHECK (http_status BETWEEN 100 AND 599),
    retrieved_at timestamptz,
    source_published_at timestamptz,
    source_event_at timestamptz,
    http_etag text,
    http_last_modified text,
    source_api_version varchar(80),
    adapter_version varchar(80),
    content_hash varchar(64) CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    retry_after text,
    retry_after_at timestamptz,
    error_code varchar(80),
    error_summary varchar(512),
    snapshot_id bigint,
    FOREIGN KEY (snapshot_id, source, station) REFERENCES crew_source_snapshot (id, source, station),
    CHECK ((result_state = 'IN_PROGRESS') = (completed_at IS NULL)),
    CHECK (completed_at IS NULL OR completed_at >= started_at),
    CHECK ((result_state = 'SUCCESS') = (snapshot_id IS NOT NULL)),
    CHECK (result_state <> 'SUCCESS' OR (source_state = 'AVAILABLE' AND retrieved_at IS NOT NULL AND content_hash IS NOT NULL)),
    CHECK ((retrieved_at IS NULL) = (content_hash IS NULL))
);
CREATE INDEX crew_sync_latest_idx ON crew_source_sync_run (source, station, started_at DESC, id DESC);
CREATE INDEX crew_sync_success_idx ON crew_source_sync_run (source, station, completed_at DESC, id DESC)
    WHERE result_state = 'SUCCESS';
CREATE INDEX crew_sync_failure_idx ON crew_source_sync_run (source, station, started_at DESC, id DESC)
    WHERE result_state IN ('SOURCE_RESULT', 'INVALID_SNAPSHOT', 'PERSISTENCE_FAILURE', 'UNEXPECTED_FAILURE');
CREATE INDEX crew_sync_retry_idx ON crew_source_sync_run (source, station, retry_after_at DESC)
    WHERE source_state = 'RATE_LIMITED';

CREATE TABLE crew_person (
    id uuid PRIMARY KEY,
    created_at timestamptz NOT NULL
);
CREATE TABLE crew_person_external_id (
    person_id uuid NOT NULL REFERENCES crew_person (id),
    source varchar(40) NOT NULL,
    external_id varchar(100) NOT NULL CHECK (length(external_id) > 0),
    PRIMARY KEY (source, external_id),
    UNIQUE (source, external_id, person_id)
);
CREATE TABLE crew_expedition (
    id uuid PRIMARY KEY,
    created_at timestamptz NOT NULL
);
CREATE TABLE crew_expedition_external_id (
    expedition_id uuid NOT NULL REFERENCES crew_expedition (id),
    source varchar(40) NOT NULL,
    external_id varchar(100) NOT NULL CHECK (length(external_id) > 0),
    PRIMARY KEY (source, external_id),
    UNIQUE (source, external_id, expedition_id)
);
CREATE TABLE crew_expedition_observation (
    snapshot_id bigint NOT NULL REFERENCES crew_source_snapshot (id),
    expedition_id uuid NOT NULL REFERENCES crew_expedition (id),
    source varchar(40) NOT NULL,
    external_id varchar(100) NOT NULL,
    name text NOT NULL CHECK (length(name) > 0),
    starts_at timestamptz,
    ends_at timestamptz,
    station varchar(16) NOT NULL CHECK (station = 'ISS'),
    source_station_external_id varchar(100) NOT NULL,
    PRIMARY KEY (snapshot_id, expedition_id),
    FOREIGN KEY (source, external_id, expedition_id) REFERENCES crew_expedition_external_id (source, external_id, expedition_id),
    FOREIGN KEY (snapshot_id, source, station) REFERENCES crew_source_snapshot (id, source, station),
    CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at)
);
CREATE TABLE crew_person_observation (
    snapshot_id bigint NOT NULL REFERENCES crew_source_snapshot (id),
    person_id uuid NOT NULL REFERENCES crew_person (id),
    source varchar(40) NOT NULL,
    external_id varchar(100) NOT NULL,
    display_name text NOT NULL CHECK (length(display_name) > 0),
    official_profile_url text,
    source_profile_mode varchar(40),
    in_space boolean,
    biography text,
    career_present boolean NOT NULL,
    time_in_space text,
    eva_time text,
    flights_count integer CHECK (flights_count >= 0),
    spacewalks_count integer CHECK (spacewalks_count >= 0),
    first_flight timestamptz,
    last_flight timestamptz,
    agency jsonb CHECK (agency IS NULL OR jsonb_typeof(agency) = 'object'),
    nationalities jsonb NOT NULL CHECK (jsonb_typeof(nationalities) = 'array'),
    media jsonb CHECK (media IS NULL OR jsonb_typeof(media) = 'object'),
    PRIMARY KEY (snapshot_id, person_id),
    FOREIGN KEY (source, external_id, person_id) REFERENCES crew_person_external_id (source, external_id, person_id),
    FOREIGN KEY (snapshot_id, source) REFERENCES crew_source_snapshot (id, source),
    CHECK (career_present OR (time_in_space IS NULL AND eva_time IS NULL AND flights_count IS NULL
        AND spacewalks_count IS NULL AND first_flight IS NULL AND last_flight IS NULL))
);
CREATE TABLE crew_assignment_observation (
    snapshot_id bigint NOT NULL,
    expedition_id uuid NOT NULL,
    person_id uuid NOT NULL,
    source varchar(40) NOT NULL,
    external_id varchar(100),
    role varchar(40) NOT NULL CHECK (role IN ('COMMANDER', 'FLIGHT_ENGINEER', 'OTHER', 'UNKNOWN')),
    source_role_label text,
    valid_from timestamptz,
    valid_until timestamptz,
    PRIMARY KEY (snapshot_id, expedition_id, person_id),
    UNIQUE (snapshot_id, source, external_id),
    FOREIGN KEY (snapshot_id, expedition_id) REFERENCES crew_expedition_observation (snapshot_id, expedition_id),
    FOREIGN KEY (snapshot_id, person_id) REFERENCES crew_person_observation (snapshot_id, person_id),
    CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until >= valid_from)
);

-- Snapshot-owned observations are append-only. Retention needs an explicit future policy.
CREATE FUNCTION crew_reject_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Crew source history is immutable' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER crew_snapshot_immutable BEFORE UPDATE OR DELETE ON crew_source_snapshot
    FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation();
CREATE TRIGGER crew_expedition_observation_immutable BEFORE UPDATE OR DELETE ON crew_expedition_observation
    FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation();
CREATE TRIGGER crew_person_observation_immutable BEFORE UPDATE OR DELETE ON crew_person_observation
    FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation();
CREATE TRIGGER crew_assignment_observation_immutable BEFORE UPDATE OR DELETE ON crew_assignment_observation
    FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation();
CREATE TRIGGER crew_person_mapping_immutable BEFORE UPDATE OR DELETE ON crew_person_external_id
    FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation();
CREATE TRIGGER crew_expedition_mapping_immutable BEFORE UPDATE OR DELETE ON crew_expedition_external_id
    FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation();
