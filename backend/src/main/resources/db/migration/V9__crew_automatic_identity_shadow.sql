-- ADR-0015. Entirely independent shadow overlay; V1–V8 rows and constraints are preserved.
CREATE TABLE crew_auto_release (
 model_version varchar(100) NOT NULL, policy_version varchar(120) NOT NULL,
 feature_schema varchar(100) NOT NULL, model_sha varchar(64) NOT NULL CHECK(model_sha ~ '^[0-9a-f]{64}$'),
 lexical_sha varchar(64) NOT NULL CHECK(lexical_sha ~ '^[0-9a-f]{64}$'),
 match_threshold double precision NOT NULL CHECK(match_threshold BETWEEN 0 AND 1),
 minimum_margin double precision NOT NULL CHECK(minimum_margin BETWEEN 0 AND 1),
 policy jsonb NOT NULL CHECK(jsonb_typeof(policy)='object'),
 PRIMARY KEY(model_version,policy_version), UNIQUE(model_version,policy_version,feature_schema,model_sha)
);
CREATE TABLE crew_auto_identity (
 identity_key varchar(240) PRIMARY KEY, provider varchar(10) NOT NULL CHECK(provider IN ('LL2','NASA')),
 entity_kind varchar(40) NOT NULL CHECK(entity_kind IN ('PERSON','EDITORIAL_SLOT','OPERATIONAL_SUBJECT','PERSONAL_RESOURCE')),
 incarnation integer NOT NULL DEFAULT 1 CHECK(incarnation>0),
 CHECK((provider='LL2' AND entity_kind='PERSON' AND identity_key LIKE 'LL2:PERSON:%') OR provider='NASA'),
 UNIQUE(identity_key,provider)
);
CREATE TABLE crew_auto_observation (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 identity_key varchar(240) NOT NULL REFERENCES crew_auto_identity(identity_key),
 evidence_hash varchar(64) NOT NULL CHECK(evidence_hash ~ '^[0-9a-f]{64}$'),
 extractor_version varchar(100) NOT NULL,
 evidence jsonb NOT NULL CHECK(jsonb_typeof(evidence)='object'),
 known_at timestamptz NOT NULL, UNIQUE(identity_key,evidence_hash,extractor_version), UNIQUE(id,identity_key)
);
-- Mutable input head preserves A→B→A selection; every observation and decision remains immutable.
CREATE TABLE crew_auto_input_head (
 identity_key varchar(240) PRIMARY KEY REFERENCES crew_auto_identity(identity_key),
 observation_id bigint NOT NULL,
 FOREIGN KEY(observation_id,identity_key) REFERENCES crew_auto_observation(id,identity_key)
);
CREATE TABLE crew_auto_candidate (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_key varchar(240) NOT NULL, source_provider varchar(10) NOT NULL DEFAULT 'NASA' CHECK(source_provider='NASA'),
 candidate_key varchar(240) NOT NULL, candidate_provider varchar(10) NOT NULL DEFAULT 'LL2' CHECK(candidate_provider='LL2'),
 FOREIGN KEY(source_key,source_provider) REFERENCES crew_auto_identity(identity_key,provider),
 FOREIGN KEY(candidate_key,candidate_provider) REFERENCES crew_auto_identity(identity_key,provider),
 CHECK(source_key<>candidate_key), UNIQUE(source_key,candidate_key), UNIQUE(id,source_key)
);
CREATE TABLE crew_auto_feature_snapshot (
 snapshot_hash varchar(64) PRIMARY KEY CHECK(snapshot_hash ~ '^[0-9a-f]{64}$'),
 source_observation_id bigint NOT NULL REFERENCES crew_auto_observation(id),
 feature_schema varchar(100) NOT NULL, payload jsonb NOT NULL CHECK(jsonb_typeof(payload)='object'),
 serialized_payload text NOT NULL CHECK(payload=serialized_payload::jsonb),
 CHECK(snapshot_hash=encode(sha256(convert_to(serialized_payload,'UTF8')),'hex'))
);
CREATE TABLE crew_auto_decision_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_key varchar(240) NOT NULL REFERENCES crew_auto_identity(identity_key),
 candidate_id bigint, FOREIGN KEY(candidate_id,source_key) REFERENCES crew_auto_candidate(id,source_key),
 predecessor_id bigint REFERENCES crew_auto_decision_revision(id),
 outcome varchar(30) NOT NULL CHECK(outcome IN ('AUTO_MATCH','AUTO_SEPARATE','AUTO_DEFER')),
 actor varchar(40) NOT NULL DEFAULT 'MACHINE' CHECK(actor='MACHINE'),
 method varchar(80) NOT NULL DEFAULT 'FROZEN_CALIBRATED_SHADOW' CHECK(method='FROZEN_CALIBRATED_SHADOW'),
 probability double precision NOT NULL CHECK(probability BETWEEN 0 AND 1),
 runner_key varchar(240) REFERENCES crew_auto_identity(identity_key),
 runner_probability double precision NOT NULL CHECK(runner_probability BETWEEN 0 AND 1),
 margin double precision NOT NULL CHECK(margin BETWEEN -1 AND 1),
 model_version varchar(100) NOT NULL, policy_version varchar(120) NOT NULL,
 feature_schema varchar(100) NOT NULL, model_sha varchar(64) NOT NULL,
 FOREIGN KEY(model_version,policy_version,feature_schema,model_sha) REFERENCES crew_auto_release(model_version,policy_version,feature_schema,model_sha),
 snapshot_hash varchar(64) NOT NULL REFERENCES crew_auto_feature_snapshot(snapshot_hash),
 witnesses jsonb NOT NULL CHECK(jsonb_typeof(witnesses)='array'),
 conflicts jsonb NOT NULL CHECK(jsonb_typeof(conflicts)='array'),
 reasons jsonb NOT NULL CHECK(jsonb_typeof(reasons)='array'),
 known_at timestamptz NOT NULL, evaluated_at timestamptz NOT NULL CHECK(evaluated_at>=known_at),
 CHECK(outcome<>'AUTO_MATCH' OR (candidate_id IS NOT NULL AND jsonb_array_length(witnesses)>0 AND jsonb_array_length(conflicts)=0)),
 UNIQUE(source_key,snapshot_hash,model_version,policy_version,predecessor_id)
);
CREATE UNIQUE INDEX crew_auto_one_root_idx ON crew_auto_decision_revision(source_key) WHERE predecessor_id IS NULL;
CREATE UNIQUE INDEX crew_auto_one_successor_idx ON crew_auto_decision_revision(predecessor_id) WHERE predecessor_id IS NOT NULL;
CREATE INDEX crew_auto_decision_latest_idx ON crew_auto_decision_revision(source_key,id DESC);
CREATE TABLE crew_auto_decision_evidence (
 decision_id bigint NOT NULL REFERENCES crew_auto_decision_revision(id),
 observation_id bigint NOT NULL REFERENCES crew_auto_observation(id),
 PRIMARY KEY(decision_id,observation_id)
);
CREATE TABLE crew_auto_graph_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 predecessor_id bigint REFERENCES crew_auto_graph_revision(id),
 graph_hash varchar(64) NOT NULL CHECK(graph_hash ~ '^[0-9a-f]{64}$'),
 components jsonb NOT NULL CHECK(jsonb_typeof(components)='array'), applied_at timestamptz NOT NULL,
 UNIQUE(predecessor_id)
);
CREATE TABLE crew_auto_graph_application (
 graph_id bigint NOT NULL REFERENCES crew_auto_graph_revision(id),
 decision_id bigint NOT NULL REFERENCES crew_auto_decision_revision(id), PRIMARY KEY(graph_id,decision_id)
);
CREATE TABLE crew_auto_job (
 job_key varchar(250) PRIMARY KEY, job_kind varchar(20) NOT NULL CHECK(job_kind IN ('IMPORT','EVALUATE')),
 identity_key varchar(240) REFERENCES crew_auto_identity(identity_key),
 generation bigint NOT NULL DEFAULT 1 CHECK(generation>0), completed_generation bigint NOT NULL DEFAULT 0 CHECK(completed_generation>=0 AND completed_generation<=generation),
 available_at timestamptz NOT NULL, enqueued_at timestamptz NOT NULL,
 lease_until timestamptz, lease_token uuid, attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 8),
 failed boolean NOT NULL DEFAULT false, last_error varchar(200), last_success_at timestamptz,
 CHECK((lease_until IS NULL)=(lease_token IS NULL)),
 CHECK((job_kind='EVALUATE')=(identity_key IS NOT NULL)), CHECK(available_at>=enqueued_at)
);
CREATE INDEX crew_auto_job_due_idx ON crew_auto_job(available_at,job_key) WHERE NOT failed;
CREATE TABLE crew_auto_sweep_lease (singleton boolean PRIMARY KEY CHECK(singleton), next_at timestamptz NOT NULL);
