CREATE FUNCTION crew_auto_check_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(73491,5);
 IF NEW.predecessor_id IS DISTINCT FROM (SELECT id FROM crew_auto_decision_revision WHERE source_key=NEW.source_key ORDER BY id DESC LIMIT 1) THEN
  RAISE EXCEPTION 'Automatic revision predecessor is not current for source' USING ERRCODE='23514';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM crew_auto_feature_snapshot s JOIN crew_auto_observation o ON o.id=s.source_observation_id
   WHERE s.snapshot_hash=NEW.snapshot_hash AND o.identity_key=NEW.source_key AND s.feature_schema=NEW.feature_schema) THEN
  RAISE EXCEPTION 'Automatic feature ownership mismatch' USING ERRCODE='23514';
 END IF;
 IF NEW.outcome='AUTO_MATCH' AND NOT EXISTS(SELECT 1 FROM crew_auto_release r WHERE r.model_version=NEW.model_version AND r.policy_version=NEW.policy_version
   AND NEW.probability>=r.match_threshold AND NEW.probability>=NEW.runner_probability+r.minimum_margin) THEN
  RAISE EXCEPTION 'Automatic match violates release threshold/margin' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_auto_decision_lineage BEFORE INSERT ON crew_auto_decision_revision FOR EACH ROW EXECUTE FUNCTION crew_auto_check_revision();
-- Transactional source notifications. Coalesce captures; the importer only enqueues changed/blocked dependencies.
CREATE FUNCTION crew_auto_notify_source() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO crew_auto_job(job_key,job_kind,available_at,enqueued_at) VALUES('IMPORT','IMPORT',now(),now())
 ON CONFLICT(job_key) DO UPDATE SET generation=crew_auto_job.generation+1, available_at=now(),enqueued_at=now(),failed=false,attempts=0;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_auto_ll2_event AFTER INSERT ON crew_person_observation FOR EACH STATEMENT EXECUTE FUNCTION crew_auto_notify_source();
CREATE TRIGGER crew_auto_ops_event AFTER INSERT ON crew_evidence_subject FOR EACH STATEMENT EXECUTE FUNCTION crew_auto_notify_source();
CREATE TRIGGER crew_auto_editorial_event AFTER INSERT ON crew_editorial_acquisition FOR EACH STATEMENT EXECUTE FUNCTION crew_auto_notify_source();
CREATE TRIGGER crew_auto_relation_event AFTER INSERT ON crew_editorial_resource_relation FOR EACH STATEMENT EXECUTE FUNCTION crew_auto_notify_source();
