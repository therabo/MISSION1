CREATE FUNCTION crew_membership_check_children()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
 IF TG_TABLE_NAME='crew_membership_projection_member' THEN
  IF NOT EXISTS(SELECT 1 FROM crew_person_external_id x WHERE x.source='LAUNCH_LIBRARY_2' AND x.person_id=NEW.person_id AND 'LL2:PERSON:'||x.external_id=NEW.human_key) THEN
   RAISE EXCEPTION 'Shadow human must be its typed LL2 provider anchor' USING ERRCODE='23514';
  END IF;
  IF NEW.departure_evidence_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_verification_evidence e WHERE e.id=NEW.departure_evidence_id AND e.evidence_type='PERSON_DEPARTED_STATION' AND e.assertion='COMPLETED') THEN
   RAISE EXCEPTION 'Member veto is not a completed named departure' USING ERRCODE='23514';
  END IF;
 ELSIF TG_TABLE_NAME='crew_membership_projection_evidence' THEN
  IF NOT EXISTS(SELECT 1 FROM crew_verification_evidence e JOIN crew_membership_projection_revision p ON p.id=NEW.projection_id WHERE e.id=NEW.evidence_id AND e.document_id=NEW.document_id AND p.input_cut->'evidence' @> to_jsonb(ARRAY[NEW.evidence_id])) THEN
   RAISE EXCEPTION 'Wrong operational evidence cut' USING ERRCODE='23514';
  END IF;
 ELSE
  IF NEW.sync_run_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_source_sync_run r JOIN crew_membership_projection_revision p ON p.id=NEW.projection_id WHERE r.id=NEW.sync_run_id AND r.completed_at<=p.evaluated_at AND (NEW.document_id IS NULL OR r.verification_document_id=NEW.document_id)) THEN
   RAISE EXCEPTION 'Wrong source run/capture cut' USING ERRCODE='23514';
  END IF;
  IF NEW.acquisition_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_resource_acquisition a JOIN crew_membership_projection_revision p ON p.id=NEW.projection_id WHERE a.id=NEW.acquisition_id AND a.completed_at<=p.evaluated_at AND a.stream=NEW.stream) THEN
   RAISE EXCEPTION 'Wrong editorial health cut' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $function$;

CREATE FUNCTION crew_membership_check_revision()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE pin record;
BEGIN
 FOR pin IN SELECT * FROM (VALUES
  ('ll2_run_id','ll2Run'),('ll2_snapshot_id','ll2Snapshot'),
  ('roster_acquisition_id','rosterAcquisition'),('roster_id','roster'),
  ('topic_acquisition_id','topicAcquisition'),('topic_count_fact_id','topicCountFact'),
  ('graph_id','graph'),('operational_run_id','operationalRun'),('operational_attempt_id','operationalAttempt')
 ) fields(column_name,cut_key) LOOP
  IF to_jsonb(NEW)->pin.column_name IS DISTINCT FROM NEW.input_cut->pin.cut_key THEN
   RAISE EXCEPTION 'Serialized and relational input cut disagree' USING ERRCODE='23514';
  END IF;
 END LOOP;
 PERFORM pg_advisory_xact_lock(73491,6);
 IF NEW.predecessor_id IS DISTINCT FROM (SELECT id FROM crew_membership_projection_revision ORDER BY id DESC LIMIT 1) THEN
  RAISE EXCEPTION 'Shadow projection predecessor is not current' USING ERRCODE='23514';
