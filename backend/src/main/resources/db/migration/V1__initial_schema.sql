CREATE FUNCTION crew_operational_subject_binding_check()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
 PERFORM pg_advisory_xact_lock(73491,10);
 IF NEW.predecessor_id IS DISTINCT FROM (SELECT id FROM crew_operational_subject_binding_revision WHERE binding_key=NEW.binding_key ORDER BY id DESC LIMIT 1) THEN
  RAISE EXCEPTION 'operational subject binding predecessor is not current' USING ERRCODE='23514';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM crew_verification_evidence e JOIN crew_source_document d ON d.id=NEW.document_id
   JOIN crew_document_evidence de ON de.document_id=d.id AND de.evidence_id=e.id
   WHERE e.id=NEW.evidence_id AND e.evidence_hash=NEW.evidence_hash AND d.content_hash=NEW.document_hash AND d.retrieved_at<=NEW.known_at) THEN
  RAISE EXCEPTION 'operational subject binding exact source lineage mismatch' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM crew_subject_version_link v WHERE v.evidence_id=NEW.evidence_id AND v.subject_index=NEW.subject_index) THEN
  IF NOT EXISTS(SELECT 1 FROM crew_subject_version_link v WHERE v.evidence_id=NEW.evidence_id AND v.subject_index=NEW.subject_index
    AND v.subject_key=NEW.subject_key AND v.version_key=NEW.source_version) THEN
   RAISE EXCEPTION 'operational subject binding subject version mismatch' USING ERRCODE='23514';
  END IF;
 ELSE
  IF NEW.subject_key<>'unassociated:'||NEW.evidence_id||':'||NEW.subject_index OR NEW.source_version<>encode(sha256(convert_to(NEW.subject_key||':'||NEW.evidence_hash,'UTF8')),'hex') THEN
   RAISE EXCEPTION 'operational subject binding unassociated source key mismatch' USING ERRCODE='23514';
  END IF;
 END IF;
 IF NOT EXISTS(SELECT 1 FROM crew_evidence_subject s WHERE s.evidence_id=NEW.evidence_id AND s.subject_index=NEW.subject_index
   AND s.display_name=NEW.input_cut->'subject'->>'name') THEN
  RAISE EXCEPTION 'operational subject binding source mention mismatch' USING ERRCODE='23514';
 END IF;
 IF NEW.outcome='AUTO_MATCH' AND (
  jsonb_array_length(NEW.reasons)<>0 OR NEW.margin<(SELECT (policy->>'margin')::double precision FROM crew_operational_subject_binding_release WHERE version=NEW.release_version)
  OR NEW.probability<(SELECT (policy->>CASE WHEN NEW.input_cut->'subject'->>'type'='PERSON_DEPARTED_STATION' THEN 'departure' ELSE 'observation' END)::double precision FROM crew_operational_subject_binding_release WHERE version=NEW.release_version)
  OR NOT EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.result->'evaluation'->'candidates') c
    WHERE c->>'key'=NEW.target_provider_key AND (c->>'qualifiedWitness')::boolean
      AND (c->>'temporal')::boolean AND (c->>'compatibleName')::boolean
      AND jsonb_array_length(c->'contradictions')=0 AND jsonb_array_length(c->'proofs')>0)) THEN
  RAISE EXCEPTION 'operational subject binding match lacks qualified policy gates' USING ERRCODE='23514';
 END IF;
 IF NEW.target_person_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM crew_person_external_id x
   JOIN crew_person_observation o ON o.person_id=x.person_id AND o.source=x.source AND o.external_id=x.external_id
   WHERE x.source='LAUNCH_LIBRARY_2' AND 'LL2:PERSON:'||x.external_id=NEW.target_provider_key
   AND (x.person_id=NEW.target_person_id OR EXISTS(SELECT 1 FROM crew_person_equivalence_decision q
     WHERE q.alias_id=x.person_id AND q.representative_id=NEW.target_person_id AND q.status='ACTIVE' AND q.known_at<=NEW.known_at))) THEN
  RAISE EXCEPTION 'operational subject binding target lacks existing publishable provider anchor' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $function$;

