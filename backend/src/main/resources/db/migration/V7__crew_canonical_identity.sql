-- ADR-0013. Additive decisions only; original UUIDs, mappings and V3--V6 histories survive.
CREATE TABLE crew_identity_binding_version (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 declaration_key varchar(100) NOT NULL,
 source varchar(40) NOT NULL CHECK(source IN ('LAUNCH_LIBRARY_2','NASA_OFFICIAL')),
 entity_kind varchar(60) NOT NULL CHECK(entity_kind IN ('PERSON','PERSON_PROFILE_RESOURCE','PERSON_PROFILE_TOPIC_RESOURCE')),
 external_key varchar(150) NOT NULL CHECK(length(external_key)>0),
 person_id uuid REFERENCES crew_person(id),
 status varchar(20) NOT NULL CHECK(status IN ('ACTIVE','PENDING','REVOKED')),
 method varchar(60) NOT NULL CHECK(method='REVIEWED_SAME_HUMAN'),
 policy_version varchar(80) NOT NULL,
 decided_at timestamptz NOT NULL,
 known_at timestamptz NOT NULL CHECK(known_at>=decided_at),
 actor_category varchar(40) NOT NULL CHECK(actor_category IN ('HUMAN_APPROVED','MAINTAINER_REVIEWED')),
 predecessor_id bigint UNIQUE REFERENCES crew_identity_binding_version(id),
 context jsonb NOT NULL CHECK(jsonb_typeof(context)='object' AND octet_length(context::text)<=8192),
 CHECK((status<>'ACTIVE' OR person_id IS NOT NULL) AND (status<>'PENDING' OR person_id IS NULL))
);
CREATE UNIQUE INDEX crew_binding_root_idx ON crew_identity_binding_version(source,entity_kind,external_key) WHERE predecessor_id IS NULL;
CREATE INDEX crew_binding_knowledge_idx ON crew_identity_binding_version(source,entity_kind,external_key,known_at DESC,id DESC);
CREATE INDEX crew_binding_person_idx ON crew_identity_binding_version(person_id,known_at DESC,id DESC);
CREATE TABLE crew_person_equivalence_decision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 declaration_key varchar(100) NOT NULL,
 left_person_id uuid NOT NULL REFERENCES crew_person(id),
 right_person_id uuid NOT NULL REFERENCES crew_person(id),
 representative_id uuid NOT NULL REFERENCES crew_person(id),
 alias_id uuid GENERATED ALWAYS AS (CASE WHEN representative_id=left_person_id THEN right_person_id ELSE left_person_id END) STORED,
 status varchar(20) NOT NULL CHECK(status IN ('ACTIVE','REVOKED')),
 method varchar(60) NOT NULL CHECK(method='REVIEWED_SAME_HUMAN'),
 policy_version varchar(80) NOT NULL,
 decided_at timestamptz NOT NULL,
 known_at timestamptz NOT NULL CHECK(known_at>=decided_at),
 actor_category varchar(40) NOT NULL CHECK(actor_category IN ('HUMAN_APPROVED','MAINTAINER_REVIEWED')),
 predecessor_id bigint UNIQUE REFERENCES crew_person_equivalence_decision(id),
 CHECK(left_person_id<right_person_id),
 CHECK(representative_id IN (left_person_id,right_person_id))
);
CREATE UNIQUE INDEX crew_equivalence_root_idx ON crew_person_equivalence_decision(left_person_id,right_person_id) WHERE predecessor_id IS NULL;
CREATE INDEX crew_equivalence_alias_idx ON crew_person_equivalence_decision(alias_id,known_at DESC,id DESC);
CREATE INDEX crew_equivalence_representative_idx ON crew_person_equivalence_decision(representative_id,known_at DESC,id DESC);
CREATE VIEW crew_active_equivalence AS
 SELECT * FROM (SELECT DISTINCT ON(left_person_id,right_person_id) * FROM crew_person_equivalence_decision
 ORDER BY left_person_id,right_person_id,known_at DESC,id DESC) latest WHERE status='ACTIVE';
CREATE VIEW crew_active_identity_binding AS
 SELECT * FROM (SELECT DISTINCT ON(source,entity_kind,external_key) * FROM crew_identity_binding_version
 ORDER BY source,entity_kind,external_key,known_at DESC,id DESC) latest WHERE status='ACTIVE';
CREATE TABLE crew_identity_decision_evidence (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 binding_id bigint REFERENCES crew_identity_binding_version(id),
 equivalence_id bigint REFERENCES crew_person_equivalence_decision(id),
 resolution_id bigint REFERENCES crew_identity_resolution(id),
 source_category varchar(40) NOT NULL CHECK(source_category IN ('PRIMARY_OFFICIAL','SECONDARY_STRUCTURED','RETAINED_SOURCE')),
 evidence_role varchar(80) NOT NULL,
 source_url text NOT NULL CHECK(length(source_url)<=2048 AND source_url ~ '^https://'),
 captured_at timestamptz NOT NULL,
 capture_hash varchar(64) NOT NULL CHECK(capture_hash ~ '^[0-9a-f]{64}$'),
 locator varchar(512) NOT NULL,
 summary text NOT NULL CHECK(length(summary) BETWEEN 1 AND 2000),
 retained_evidence_id bigint REFERENCES crew_verification_evidence(id),
 CHECK(num_nonnulls(binding_id,equivalence_id,resolution_id)=1),
 UNIQUE NULLS NOT DISTINCT(binding_id,equivalence_id,resolution_id,evidence_role,source_url,capture_hash,locator)
);
CREATE INDEX crew_identity_proof_binding_idx ON crew_identity_decision_evidence(binding_id);
CREATE INDEX crew_identity_proof_equivalence_idx ON crew_identity_decision_evidence(equivalence_id);
CREATE FUNCTION crew_check_identity_binding() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE old crew_identity_binding_version;
BEGIN
 PERFORM pg_advisory_xact_lock(73491,1);
 SELECT * INTO old FROM crew_identity_binding_version WHERE source=NEW.source AND entity_kind=NEW.entity_kind AND external_key=NEW.external_key ORDER BY known_at DESC,id DESC LIMIT 1;
 IF FOUND AND (NEW.predecessor_id IS DISTINCT FROM old.id OR NEW.known_at<old.known_at) THEN
  RAISE EXCEPTION 'Identity binding must explicitly supersede its latest decision' USING ERRCODE='23514';
 ELSIF NOT FOUND AND NEW.predecessor_id IS NOT NULL THEN
  RAISE EXCEPTION 'Binding predecessor has a different typed identity' USING ERRCODE='23514';
 END IF;
 IF NEW.status='ACTIVE' AND EXISTS(SELECT 1 FROM crew_active_equivalence WHERE alias_id=NEW.person_id) THEN
  RAISE EXCEPTION 'Active binding must target a canonical representative' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION crew_check_equivalence() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE old crew_person_equivalence_decision; earlier uuid; candidate_alias uuid;
BEGIN
 PERFORM pg_advisory_xact_lock(73491,1);
 candidate_alias := CASE WHEN NEW.representative_id=NEW.left_person_id THEN NEW.right_person_id ELSE NEW.left_person_id END;
 SELECT id INTO earlier FROM crew_person WHERE id IN (NEW.left_person_id,NEW.right_person_id) ORDER BY created_at,id LIMIT 1;
 IF earlier IS DISTINCT FROM NEW.representative_id THEN
  RAISE EXCEPTION 'Earlier retained UUID must represent the reviewed pair' USING ERRCODE='23514';
 END IF;
 SELECT * INTO old FROM crew_person_equivalence_decision WHERE left_person_id=NEW.left_person_id AND right_person_id=NEW.right_person_id ORDER BY known_at DESC,id DESC LIMIT 1;
 IF FOUND AND (NEW.predecessor_id IS DISTINCT FROM old.id OR NEW.known_at<old.known_at) THEN
  RAISE EXCEPTION 'Equivalence must explicitly supersede its latest decision' USING ERRCODE='23514';
 ELSIF NOT FOUND AND NEW.predecessor_id IS NOT NULL THEN
  RAISE EXCEPTION 'Equivalence predecessor has a different pair' USING ERRCODE='23514';
 END IF;
 IF NEW.status='ACTIVE' AND EXISTS(SELECT 1 FROM crew_active_equivalence e WHERE
  (e.alias_id=candidate_alias AND e.representative_id<>NEW.representative_id)
  OR e.alias_id=NEW.representative_id OR e.representative_id=candidate_alias) THEN
  RAISE EXCEPTION 'Conflicting representative, cycle or implicit transitive equivalence' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER crew_binding_valid BEFORE INSERT ON crew_identity_binding_version FOR EACH ROW EXECUTE FUNCTION crew_check_identity_binding();
CREATE TRIGGER crew_equivalence_valid BEFORE INSERT ON crew_person_equivalence_decision FOR EACH ROW EXECUTE FUNCTION crew_check_equivalence();
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['crew_identity_binding_version','crew_person_equivalence_decision','crew_identity_decision_evidence'] LOOP
  EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION crew_reject_history_mutation()',t||'_immutable',t);
 END LOOP;
END $$;

-- A decision and its reproducible proof must commit together, including pending declarations.
CREATE FUNCTION crew_require_identity_proof() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM crew_identity_decision_evidence e WHERE
  (TG_TABLE_NAME='crew_identity_binding_version' AND e.binding_id=NEW.id)
  OR (TG_TABLE_NAME='crew_person_equivalence_decision' AND e.equivalence_id=NEW.id)) THEN
  RAISE EXCEPTION 'Reviewed identity decision requires retained proof' USING ERRCODE='23514';
 END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER crew_binding_proof AFTER INSERT ON crew_identity_binding_version DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION crew_require_identity_proof();
CREATE CONSTRAINT TRIGGER crew_equivalence_proof AFTER INSERT ON crew_person_equivalence_decision DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION crew_require_identity_proof();
